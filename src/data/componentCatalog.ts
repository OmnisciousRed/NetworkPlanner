import type {
  ComponentTemplate,
  CpuSpecs,
  MainboardSpecs,
  RamSpecs,
  StorageSpecs,
} from '@/models'
import { cpuSizeForSocket, pcieCardSize, storageNaturalSize } from '@/utils/generators'

/* ------------------------------------------------------------------ */
/* helpers                                                             */
/* ------------------------------------------------------------------ */

function cpu(
  id: string,
  subgroup: string,
  name: string,
  manufacturer: string,
  specs: CpuSpecs,
): ComponentTemplate {
  return {
    id,
    kind: 'cpu',
    group: 'CPU',
    subgroup,
    name,
    manufacturer,
    model: name,
    powerW: specs.tdpW,
    weightKg: 0.1,
    size: cpuSizeForSocket(specs.socket),
    specs,
  }
}

function ram(id: string, subgroup: string, name: string, manufacturer: string, specs: RamSpecs): ComponentTemplate {
  return {
    id,
    kind: 'ram',
    group: 'RAM',
    subgroup,
    name,
    manufacturer,
    model: name,
    powerW: specs.memoryType === 'DDR5' ? (specs.registered ? 6 : 4) : 3.5,
    weightKg: 0.03,
    size: { w: 133, h: 31 },
    specs,
  }
}

function storage(
  id: string,
  subgroup: string,
  name: string,
  manufacturer: string,
  powerW: number,
  specs: StorageSpecs,
): ComponentTemplate {
  return {
    id,
    kind: 'storage',
    group: 'Storage',
    subgroup,
    name,
    manufacturer,
    model: name,
    powerW,
    weightKg: specs.formFactor === '3.5"' ? 0.7 : specs.formFactor === '2.5"' || specs.formFactor === 'U.2' ? 0.12 : 0.01,
    size: storageNaturalSize(specs.formFactor),
    specs,
  }
}

function nic(
  id: string,
  subgroup: string,
  name: string,
  manufacturer: string,
  portCount: number,
  speed: number,
  connector: 'RJ45' | 'SFP+' | 'SFP28' | 'QSFP28' | 'SFP',
  pcieLanes: 1 | 4 | 8 | 16,
  pcieGen: number,
  powerW: number,
  lengthMm = 150,
  lowProfile = true,
): ComponentTemplate {
  return {
    id,
    kind: 'nic',
    group: 'Network',
    subgroup,
    name,
    manufacturer,
    model: name,
    powerW,
    weightKg: 0.15,
    size: pcieCardSize(lengthMm, lowProfile),
    specs: { portCount, speed, connector, pcieLanes, pcieGen, lowProfile, lengthMm, controller: name },
  }
}

function board(
  id: string,
  subgroup: string,
  name: string,
  manufacturer: string,
  powerW: number,
  specs: MainboardSpecs,
): ComponentTemplate {
  return {
    id,
    kind: 'mainboard',
    group: 'Mainboard',
    subgroup,
    name,
    manufacturer,
    model: name,
    powerW,
    weightKg: specs.sockets > 1 ? 1.4 : 0.9,
    specs,
  }
}

